# ---------- main ----------
def main():
    ap = argparse.ArgumentParser(); ap.add_argument("file"); ap.add_argument("--out")
    a = ap.parse_args()
    src = os.path.abspath(a.file); out = os.path.abspath(a.out or os.path.join(os.path.dirname(src), "ai-check"))
    fname = os.path.basename(src); stem, ext = os.path.splitext(fname); cname = f"{stem}.cleaned{ext}"
    ensure_service()
    data = read_shared(src); os.makedirs(out, exist_ok=True)
    wj = lambda name, o: json.dump(o, open(os.path.join(out, name), "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    base = {"file": base64.b64encode(data).decode(), "name": fname}
    ins = post("/inspect", base); wj("inspect_raw.json", ins)
    cl = post("/clean", dict(base, options={"detect_before": True, "detect_after": True}))
    if "cleaned" not in cl:
        print("clean with options failed:", str(cl)[:300]); cl = post("/clean", base)
    if "cleaned" not in cl or "report" not in ins:
        print("ERROR: service returned an error:", str(ins)[:300], str(cl)[:300]); sys.exit(1)
    cd = base64.b64decode(cl.pop("cleaned")); wj("clean_raw.json", cl)
    cpath = os.path.join(out, cname); open(cpath, "wb").write(cd)
    actions = cl["report"].get("actions", [])
    det = {k: cl.get(k) or cl["report"].get(k) for k in ("detect_before", "detect_after", "detections") if cl.get(k) or cl["report"].get(k)} \
        or "none returned by /clean (inspect: no watermark detector configured, stylometry null, synthid null)"
    if ext.lower() == ".docx":
        r = docx_analysis(data, cd, ins, cl)
    else:  # generic: no zip diff
        conf = ins["report"].get("findings_confidence", [])
        r = dict(parts=[], md=[], text_identical=None, pb=None, pa=None, rb=None, ra=None, png_flat=([], []), png_per={},
                 F=[{"id": t, "part": t.split(":", 1)[0].strip(), "value": t, "confidence": conf[i] if i < len(conf) else "informational",
                     "why": why_for(t), "fixed": not cl["report"].get("post_findings"), "before": {}, "after": {}}
                    for i, t in enumerate(ins["report"].get("findings", []))])
    ev = {"original": {"path": src, "size": len(data)}, "cleaned": {"path": cpath, "size": len(cd)}, "findings": r["F"], "parts": r["parts"],
          "metadata_diff": r["md"], "text_identical": r["text_identical"], "paragraphs_before": r["pb"], "paragraphs_after": r["pa"],
          "runs_before": r["rb"], "runs_after": r["ra"],
          "extra_cleaned_by_tool": {"png_text_chunks_before": r["png_flat"][0], "png_text_chunks_after": r["png_flat"][1],
                                    "png_text_chunks": r["png_per"], "tool_actions": actions},
          "detections": det, "not_checked": NOT_CHECKED}
    wj("evidence.json", ev)
    page = build_html(ev, fname, cname)
    hp = os.path.join(out, "cleaning-visual.html"); open(hp, "w", encoding="utf-8").write(page)
    # every number in the page must appear in evidence.json
    s = open(os.path.join(out, "evidence.json"), encoding="utf-8").read()
    body = html.unescape(re.sub(r"<[^>]+>", " ", re.sub(r"<(style|title).*?</\1>", "", page, flags=re.S)))
    bad = sorted({m for m in re.findall(r"\d[\d.]*\d|\d", body) if m not in s and m.replace(".", "") not in s})
    ch = sum(p["changed"] for p in r["parts"])
    print(f"\nOriginal: {len(data)} B -> cleaned: {len(cd)} B")
    print(f"Parts changed: {ch} of {len(r['parts'])} | findings: {len(r['F'])} | text identical: "
          f"{'n/a' if r['text_identical'] is None else 'yes' if r['text_identical'] else 'NO'}")
    if r["pb"] is not None: print(f"paragraphs {r['pb']}/{r['pa']}, runs {r['rb']}/{r['ra']}")
    print("numbers in html not literally in evidence.json:", bad)
    print("Outputs:", out, "\n ", cpath, "\n ", hp)

if __name__ == "__main__":
    main()
