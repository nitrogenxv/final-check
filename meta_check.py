#!/usr/bin/env python3
"""meta_check.py FILE [--out OUTDIR]
Inspect + clean a file through the local watermarks-remover service, diff original vs cleaned
(zip level for .docx) and write inspect_raw.json, clean_raw.json, evidence.json, cleaning-visual.html.
Exit codes: 0 ok, 2 service unavailable. Never modifies the original. Stdlib only."""
import argparse, base64, html, io, json, os, re, struct, subprocess, sys, time, urllib.request, urllib.error, zipfile

BASE = os.environ.get("WATERMARKS_SERVICE_URL", "http://127.0.0.1:8765").rstrip("/")
# where the watermarks-remover repo was cloned (install.ps1 puts it next to this repo)
COMPOSE_DIR = os.environ.get("WATERMARKS_REMOVER_DIR") or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "watermarks-remover")

# ---------- service ----------
def health():
    try:
        return json.load(urllib.request.urlopen(BASE + "/health", timeout=5)).get("ok") is True
    except Exception:
        return False

def ensure_service():
    if health(): return
    print("Η υπηρεσία δεν απαντά, δοκιμάζω docker compose up -d ... / Service down, trying docker compose up -d ...")
    try: subprocess.run(["docker", "compose", "up", "-d"], cwd=COMPOSE_DIR, timeout=300)
    except Exception as e: print("docker:", e)
    for _ in range(60):
        if health(): return
        time.sleep(2)
    print("ΣΦΑΛΜΑ: η υπηρεσία watermarks-remover δεν είναι διαθέσιμη. Ανοίξτε το Docker Desktop και ξαναδοκιμάστε.\n"
          f"ERROR: watermarks-remover service unavailable at {BASE}. Docker Desktop must be running.")
    sys.exit(2)

def post(ep, body):
    r = urllib.request.Request(BASE + ep, json.dumps(body).encode(), {"Content-Type": "application/json"})
    try: return json.load(urllib.request.urlopen(r, timeout=300))
    except urllib.error.HTTPError as e: return {"_http": e.code, "_body": e.read().decode("utf8", "replace")}

def read_shared(path):
    try:
        return open(path, "rb").read()
    except PermissionError:  # locked by Word
        ps = f"$s=[IO.File]::Open('{path}','Open','Read','ReadWrite');$m=New-Object IO.MemoryStream;$s.CopyTo($m);$s.Close();[Convert]::ToBase64String($m.ToArray())"
        return base64.b64decode(subprocess.check_output(["powershell", "-NoProfile", "-c", ps]))

# ---------- analysis helpers ----------
def fields(b):
    x = b.decode("utf8", "replace")
    return {m.group(1): m.group(2) for m in re.finditer(r'<([A-Za-z][\w]*:?[\w]*)(?:\s[^>]*)?>([^<]*)</\1>', x)}

def paras(b):
    x = b.decode("utf8", "replace")
    ps = re.findall(r'<w:p[ >].*?</w:p>', x, re.S)
    return ["".join(re.findall(r'<w:t(?:\s[^>]*)?>([^<]*)</w:t>', p)) for p in ps], len(re.findall(r'<w:r[ >]', x))

def png_text(b):
    out = []
    if b[:8] != b"\x89PNG\r\n\x1a\n": return out
    i = 8
    while i + 8 <= len(b):
        l = struct.unpack(">I", b[i:i + 4])[0]; t = b[i + 4:i + 8].decode("latin1")
        if t in ("tEXt", "iTXt", "zTXt"): out.append([t, b[i + 8:i + 8 + l][:500].decode("latin1")])
        i += 12 + l
    return out

